// Curated opening curriculum. Every line starts from the initial position and
// is validated move-by-move against chess.js in lessons.test.ts, so a typo in a
// SAN string fails CI instead of breaking a drill.

export type Side = 'white' | 'black'

export type LessonMove = {
  san: string
  // One-line reason for the move. Shown after it is played in Learn mode and
  // after a correct answer in Drill mode.
  why: string
}

export type OpeningLesson = {
  id: string
  name: string
  eco: string
  kind: 'line' | 'trap'
  side: Side
  summary: string
  plan: string
  moves: LessonMove[]
}

export type OpeningFamily = {
  id: string
  name: string
  tier: number
  // Lower-case fragments matched against Chess.com opening labels to recommend
  // families where the player's own games produce the most mistakes.
  keywords: string[]
  lessons: OpeningLesson[]
}

export type Tier = { id: number; title: string; blurb: string }

