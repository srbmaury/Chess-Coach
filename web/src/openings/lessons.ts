export function lessonById(id: string): OpeningLesson | undefined {
  return ALL_LESSONS.find((lesson) => lesson.id === id)
}

export function familyOf(lessonId: string): OpeningFamily | undefined {
  return FAMILIES.find((family) => family.lessons.some((lesson) => lesson.id === lessonId))
}
